      SUBROUTINE INCROQ (AX,AY,AZ,AX1,AY1,AZ1,AX2,AY2,AZ2,SGR,CGR,SGS,
     1                   CGS,NB,KRV,FL,BETA,SDELX,DELY,DELR,DELI)
C
C     HALO: INCRO WITH THE QUARTIC DOUBLET-LATTICE KERNEL - WHAT MSC
C     NASTRAN AND SIMCENTER NASTRAN CALL QUARTICDLM (NASTRAN SYSTEM(270)
C     = 1, "THE NEW QUARTIC FORMULATION OF THE DOUBLET LATTICE KERNEL
C     (N5KQ)"). RODDEN, TAYLOR AND MCINTOSH, "FURTHER REFINEMENT OF THE
C     SUBSONIC DOUBLET-LATTICE METHOD", J. AIRCRAFT 35(5), 720-727,
C     1998: THE NUMERATORS OF THE INCREMENTAL OSCILLATORY KERNELS, PLANAR
C     (P1) AND NONPLANAR (P2), ARE FITTED ACROSS THE SENDING BOX'S
C     DOUBLET LINE BY A QUARTIC THROUGH FIVE POINTS (ETA = -E, -E/2, 0,
C     E/2, E) INSTEAD OF INCRO'S PARABOLA THROUGH THREE, AND THE KERNEL
C     INTEGRALS I1, I2 ARE APPROXIMATED WITH DESMARAIS' 12 TERMS INSTEAD
C     OF LASCHKA'S 11 (TKERQ). THE FIT (THE PAPER'S EQS. 15-19, 28-32)
C     AND THE CLOSED-FORM INTEGRALS (EQS. 20-25, 33-34) ARE WRITTEN AS
C     DLR'S PANELAERO WRITES THEM (BSD-3, GITHUB.COM/DLR-AE/PANELAERO,
C     VALIDATED THERE AGAINST MSC NASTRAN'S QUARTIC DLM), CHECKED HERE
C     AGAINST QUADRATURE TO 1E-13 WHERE THEY ARE EXACT AND 1E-4 WHERE THE
C     PAPER'S SERIES STANDS IN - WITH ONE CHANGE: IN THE COPLANAR LIMIT
C     (|ZETA|/E .LE. 0.001) THE NONPLANAR TERM TAKES THE SERIES ALPHA OF
C     EQ. 25, WHICH MATCHES THE QUADRATURE THERE; PANELAERO'S VALUE
C     (2E/(ETA**2-E**2)) AND IDF2'S ((2E**2/(ETA**2-E**2))**2) DO NOT.
C     IT MATTERS LITTLE: THAT NUMERATOR CARRIES ZETA (T2) AND IS NEAR 0.
C     THE ARCTANGENT IS IN ITS QUADRANT (THE PAPER'S D1, D2), WHICH
C     NASA'S IDF1 / IDF2 (THE PARABOLIC KERNEL) ARE NOT FOR A RECEIVING
C     POINT OFF THE PLANE AND WITHIN E OF THE BOX CENTRE.
C
C     INCRO'S ARGUMENTS AND RESULT FOR NB REDUCED FREQUENCIES AT ONCE
C     (KRV, DELR, DELI; NB .LE. 16 - INCRO PASSES 1, AMGK'S INCROK ITS
C     BATCH): DELR, DELI THE REAL AND IMAGINARY INCREMENTAL PART OF ONE
C     INFLUENCE COEFFICIENT PER FREQUENCY. THE SAME SPECIAL CASES FOR THE
C     RECEIVING POINT AS INCRO (ON THE LINE, IN THE PLANE, ABS(ZETA) .LE.
C     0.0001) AND THE SAME SKIPS (NO PLANAR PART WHEN T1 IS ZERO AT EVERY
C     POINT, NO NONPLANAR ONE WHEN T2 IS). THE GEOMETRY, THE REGIME, THE
C     LOGARITHM AND THE ARCTANGENT ONCE FOR ALL FREQUENCIES; THE KERNELS
C     PER FREQUENCY. EVERYTHING IN DOUBLE PRECISION; NO COMMON, NO SAVE:
C     CALLED FROM GENDP'S AND GENDK'S THREADS.
C
      INTEGER          NB
      REAL             AX,AY,AZ,AX1,AY1,AZ1,AX2,AY2,AZ2,SGR,CGR,SGS,CGS,
     1                 KRV(NB),FL,BETA,SDELX,DELY,DELR(NB),DELI(NB)
      REAL             M,BR,T1,T2,XP(5),YP(5),ZP(5)
      DOUBLE PRECISION P1R(16,5),P1I(16,5),P2R(16,5),P2I(16,5),AT1S,
     1                 AT2S,E,E2,E3,E4,Y,Z,Y2,Z2,Y4,Z4,Q,RATIO,ALPHA,S,
     2                 EPSL,D1,D2,F,XL,XMULT,A1R,A1I,B1R,B1I,C1R,C1I,
     3                 D1R,D1I,E1R,E1I,A2R,A2I,B2R,B2I,C2R,C2I,D2R,D2I,
     4                 E2R,E2I,P,DENP,DENM,PI,SERN,V(5),
     5                 G1A,G1B,G1C,G1D,G1E,H1A,H1B,H1D,H1E,W3
      INTEGER          J,N,L
      LOGICAL          I0,IA,IB
C
      PI    = 3.14159265358979324D0
      M     = SQRT(1.0 - BETA**2)
      BR    = FL/2.
      DO 5 L = 1,NB
      DELR(L) = 0.0
      DELI(L) = 0.0
    5 CONTINUE
C
C     THE FIVE POINTS OF THE DOUBLET LINE (SUBP HANDS IN THE CENTRE AND
C     THE TWO ENDS: AX1 IS ETA = -E, AX2 IS ETA = +E), AS RECEIVING POINT
C     MINUS DOUBLET POINT; ORDER -E, -E/2, 0, E/2, E. THE KERNELS AT
C     EACH, FOR EVERY FREQUENCY
C
      XP(1) = AX1
      YP(1) = AY1
      ZP(1) = AZ1
      XP(2) = 0.5*(AX+AX1)
      YP(2) = 0.5*(AY+AY1)
      ZP(2) = 0.5*(AZ+AZ1)
      XP(3) = AX
      YP(3) = AY
      ZP(3) = AZ
      XP(4) = 0.5*(AX+AX2)
      YP(4) = 0.5*(AY+AY2)
      ZP(4) = 0.5*(AZ+AZ2)
      XP(5) = AX2
      YP(5) = AY2
      ZP(5) = AZ2
      AT1S  = 0.0D0
      AT2S  = 0.0D0
      T1    = 0.0
      T2    = 0.0
      DO 10 J = 1,5
      CALL TKERQ (XP(J),YP(J),ZP(J),NB,KRV,BR,SGR,CGR,SGS,CGS,T1,T2,M,
     1            1,P1R(1,J),P1I(1,J),P2R(1,J),P2I(1,J))
      AT1S  = MAX(AT1S,DBLE(ABS(T1)))
      AT2S  = MAX(AT2S,DBLE(ABS(T2)))
   10 CONTINUE
C
C     THE RECEIVING POINT IN THE SENDING BOX'S FRAME, AS INCRO SETS IT
C
      E     = 0.5D0*DBLE(DELY)
      E2    = E*E
      E3    = E2*E
      E4    = E2*E2
      XMULT = DBLE(SDELX)/(8.0D0*PI)
      IF (AY.EQ.0.0 .AND. AZ.EQ.0.0) GO TO 20
      IF (AZ.EQ.0.0 .AND. SGS.EQ.0.0) GO TO 25
      Y     = DBLE(AY*CGS + AZ*SGS)
      Z     = DBLE(-AY*SGS + AZ*CGS)
      IF (ABS(Z) .LE. 0.0001D0) Z = 0.0D0
      GO TO 30
   20 Y     = 0.0D0
      Z     = 0.0D0
      GO TO 30
   25 Y     = DBLE(AY*CGS)
      Z     = 0.0D0
   30 Y2    = Y*Y
      Z2    = Z*Z
      Y4    = Y2*Y2
      Z4    = Z2*Z2
      Q     = Y2 + Z2 - E2
C
C     THE REGIMES (PANELAERO'S I0, IA, IR): COPLANAR, CLOSE TO THE LINE
C     OR FAR (THE SERIES, EQ. 25), THE REST (THE ARCTANGENT, EQ. 24).
C     Q = 0, THE POINT ON THE CIRCLE OF RADIUS E: RATIO IS INFINITE, THE
C     POINT IS "NEAR THE LINE" FOR THE NONPLANAR PART AND F IS THE
C     PAPER'S D2 = 1/2 LIMIT
C
      I0    = ABS(Z)/E .LE. 0.001D0
      RATIO = 0.0D0
      IF (Q .NE. 0.0D0) RATIO = 2.0D0*E*ABS(Z)/Q
      IA    = (.NOT.I0) .AND. Q.NE.0.0D0 .AND. ABS(RATIO).LE.0.3D0
      ALPHA = 0.0D0
      IF (Q .EQ. 0.0D0) GO TO 40
      S     = 0.0D0
!GCC$ NOVECTOR
      DO 35 N = 2,7
      SERN  = DBLE((-1)**N)/DBLE(2*N-1)
      S     = S + SERN*RATIO**(2*N-4)
   35 CONTINUE
      ALPHA = 4.0D0*E4/(Q*Q)*S
   40 D1    = 1.0D0
      D2    = 0.0D0
      IF (Q .EQ. 0.0D0) D1 = 0.0D0
      IF (Q .EQ. 0.0D0) D2 = 0.5D0
      IF (Q .LT. 0.0D0) D2 = 1.0D0
      IF (I0) GO TO 45
      EPSL  = ALPHA
      IF (.NOT.IA .AND. Q.NE.0.0D0)
     1   EPSL = E2/Z2*(1.0D0 - ATAN(RATIO)/RATIO)
      F     = D2*PI/ABS(Z)
      IF (Q .NE. 0.0D0) F = F + D1*2.0D0*E/Q*(1.0D0 - EPSL*Z2/E2)
      GO TO 50
   45 EPSL  = ALPHA
      F     = 0.0D0
      IF (Y2 .NE. E2) F = D1*2.0D0*E/(Y2-E2)
   50 XL    = 0.0D0
      DENM  = (Y-E)**2 + Z2
      DENP  = (Y+E)**2 + Z2
      IF (DENM.GT.0.0D0 .AND. DENP.GT.0.0D0) XL = LOG(DENM/DENP)
      IB    = (.NOT.I0) .AND.
     1        ABS(Q) .LE. 0.1D0*2.0D0*E*ABS(Z)
C
C     THE PLANAR INTEGRAL (EQ. 20) IS LINEAR IN THE QUARTIC'S
C     COEFFICIENTS: ITS WEIGHTS, ONCE
C
      G1A   = (Y2-Z2)*F + Y*XL + 2.0D0*E
      G1B   = Y*F + 0.5D0*XL
      G1C   = F
      G1D   = Y*(Y2-3.0D0*Z2)*F + 0.5D0*(3.0D0*Y2-Z2)*XL + 4.0D0*E*Y
      G1E   = (Y4-6.0D0*Y2*Z2+Z4)*F + 2.0D0*Y*(Y2-Z2)*XL
     1      + 2.0D0*E*(3.0D0*Y2-Z2+E2/3.0D0)
C
C     PER FREQUENCY: THE QUARTIC THROUGH P1 AT THE FIVE POINTS (EQS.
C     15-19), ITS INTEGRAL; THEN THE SAME FOR P2 (EQS. 28-32) WITH THE
C     NONPLANAR INTEGRAL, EQ. 33 NEAR THE LINE (1/RATIO .LE. 0.1), EQ.
C     34 ELSEWHERE
C
      DO 90 L = 1,NB
      IF (AT1S .EQ. 0.0D0) GO TO 60
      DO 52 J = 1,5
   52 V(J) = P1R(L,J)
      CALL DLMQFT (V,E,E2,E3,E4,A1R,B1R,C1R,D1R,E1R)
      DO 54 J = 1,5
   54 V(J) = P1I(L,J)
      CALL DLMQFT (V,E,E2,E3,E4,A1I,B1I,C1I,D1I,E1I)
      P     = G1A*A1R + G1B*B1R + G1C*C1R + G1D*D1R + G1E*E1R
      DELR(L) = SNGL(XMULT*P)
      P     = G1A*A1I + G1B*B1I + G1C*C1I + G1D*D1I + G1E*E1I
      DELI(L) = SNGL(XMULT*P)
   60 IF (AT2S .EQ. 0.0D0) GO TO 90
      DO 62 J = 1,5
   62 V(J) = P2R(L,J)
      CALL DLMQFT (V,E,E2,E3,E4,A2R,B2R,C2R,D2R,E2R)
      DO 64 J = 1,5
   64 V(J) = P2I(L,J)
      CALL DLMQFT (V,E,E2,E3,E4,A2I,B2I,C2I,D2I,E2I)
      CALL DLMQNP (IB,Y,Z,E,E2,E4,Y2,Z2,Y4,Z4,Q,RATIO,
     1             F,XL,EPSL,D1,D2,A2R,B2R,C2R,D2R,E2R,P)
      DELR(L) = DELR(L) + SNGL(XMULT*P)
      CALL DLMQNP (IB,Y,Z,E,E2,E4,Y2,Z2,Y4,Z4,Q,RATIO,
     1             F,XL,EPSL,D1,D2,A2I,B2I,C2I,D2I,E2I,P)
      DELI(L) = DELI(L) + SNGL(XMULT*P)
   90 CONTINUE
      RETURN
      END


      SUBROUTINE DLMQFT (PV,E,E2,E3,E4,A,B,C,D,EQ)
C
C     HALO: THE QUARTIC A S**2 + B S + C + D S**3 + EQ S**4 THROUGH THE
C     FIVE VALUES PV AT S = -E, -E/2, 0, E/2, E (RODDEN ET AL. 1998,
C     EQS. 15-19)
C
      DOUBLE PRECISION PV(5),E,E2,E3,E4,A,B,C,D,EQ
      A  = -1.0D0/(6.0D0*E2)*(PV(1) - 16.0D0*PV(2) + 30.0D0*PV(3)
     1                        - 16.0D0*PV(4) + PV(5))
      B  =  1.0D0/(6.0D0*E)*(PV(1) - 8.0D0*PV(2) + 8.0D0*PV(4) - PV(5))
      C  =  PV(3)
      D  = -2.0D0/(3.0D0*E3)*(PV(1) - 2.0D0*PV(2) + 2.0D0*PV(4) - PV(5))
      EQ =  2.0D0/(3.0D0*E4)*(PV(1) - 4.0D0*PV(2) + 6.0D0*PV(3)
     1                        - 4.0D0*PV(4) + PV(5))
      RETURN
      END


      SUBROUTINE DLMQNP (IB,Y,Z,E,E2,E4,Y2,Z2,Y4,Z4,Q,RATIO,F,XL,EPSL,
     1                   D1,D2,A,B,C,D,EQ,P)
C
C     HALO: THE NONPLANAR INTEGRAL OF THE QUARTIC NUMERATOR (RODDEN ET
C     AL. 1998, EQ. 33 WHEN IB, EQ. 34 OTHERWISE), WITHOUT THE CHORD /
C     (8 PI) FACTOR. EPSL IS EQ. 24'S OR 25'S EPSILON (THE SERIES ALPHA
C     IN THE COPLANAR LIMIT, SEE INCROQ)
C
      LOGICAL          IB
      DOUBLE PRECISION Y,Z,E,E2,E4,Y2,Z2,Y4,Z4,Q,RATIO,F,XL,EPSL,D1,D2,
     1                 A,B,C,D,EQ,P,DENP,DENM,PI,POLY,Y6,Z6,H
      PI   = 3.14159265358979324D0
      DENP = (Y+E)**2 + Z2
      DENM = (Y-E)**2 + Z2
      POLY = (Y2+Z2)*A + Y*B + C + Y*(Y2+3.0D0*Z2)*D
     1     + (Y4+6.0D0*Y2*Z2-3.0D0*Z4)*EQ
      IF (.NOT.IB) GO TO 20
      P    = 1.0D0/(2.0D0*Z2)*(F*POLY
     1     + (((Y2+Z2)*Y + (Y2-Z2)*E)*A + (Y2+Z2+Y*E)*B + (Y+E)*C
     2     + (Y4-Z4 + (Y2-3.0D0*Z2)*Y*E)*D
     3     + ((Y4-2.0D0*Y2*Z2-3.0D0*Z4)*Y + (Y4-6.0D0*Y2*Z2+Z4)*E)*EQ)
     4       /DENP
     5     - (((Y2+Z2)*Y - (Y2-Z2)*E)*A + (Y2+Z2-Y*E)*B + (Y-E)*C
     6     + (Y4-Z4 - (Y2-3.0D0*Z2)*Y*E)*D
     7     + ((Y4-2.0D0*Y2*Z2-3.0D0*Z4)*Y - (Y4-6.0D0*Y2*Z2+Z4)*E)*EQ)
     8       /DENM
     9     + Z2*XL*D + 4.0D0*Z2*(E + Y*XL)*EQ)
      RETURN
   20 IF (Q .EQ. 0.0D0) THEN
      P    = 0.0D0
      RETURN
      END IF
      Y6   = Y4*Y2
      Z6   = Z4*Z2
      H    = 0.0D0
      IF (Z2 .NE. 0.0D0 .AND. RATIO .NE. 0.0D0)
     1     H = E2/Z2*(1.0D0 - D1 - D2*PI/RATIO)
      P    = E/Q*((2.0D0*(Y2+Z2+E2)*(E2*A+C) + 4.0D0*Y*E2*B
     1     + 2.0D0*Y*(Y4-2.0D0*E2*Y2+2.0D0*Y2*Z2+3.0D0*E4+2.0D0*E2*Z2
     2     + Z4)*D
     3     + 2.0D0*(3.0D0*Y6-7.0D0*E2*Y4+5.0D0*Y4*Z2+6.0D0*E4*Y2
     4     + 6.0D0*E2*Y2*Z2-3.0D0*E2*Z4-Z6+Y2*Z4-2.0D0*E4*Z2)*EQ)
     5       /(DENP*DENM)
     6     - (D1*EPSL + H)/E2*POLY)
     7     + (0.5D0*D*XL + 2.0D0*(E + Y*XL)*EQ)
      RETURN
      END


      SUBROUTINE TKERQ (X0,Y0,Z0,NB,KRV,BR,SGR,CGR,SGS,CGS,T1,T2,M,IAPX,
     1                  P1R,P1I,P2R,P2I)
C
C     HALO: TKER'S INCREMENTAL OSCILLATORY KERNELS (IND = 1) IN DOUBLE
C     PRECISION, FOR INCROQ, AT ONE POINT FOR NB REDUCED FREQUENCIES
C     KRV - THE SAME FORMULAS, BRANCHES AND SIGNS AS TKER (RODDEN,
C     GIESING AND KALMAN 1971; THE NEGATIVE-U REFLECTIONS OF THEIR EQS.
C     A.5 AND A.9), WITH THE APPROXIMATION OF THE KERNEL INTEGRALS CHOSEN
C     BY IAPX: 0 LASCHKA'S 11 TERMS (TKER'S), 1 DESMARAIS' 12 (RODDEN ET
C     AL. 1998). RETURNS WHAT INCRO FORMS FROM TKER'S COMMON /DLM/:
C     P1 = K1RT1 - K10T1 + I K1IT1, P2 = K2RT2P - K20T2P + I K2IT2P PER
C     FREQUENCY, AND T1, T2 AS TKER LEAVES THEM (T2 = 100 T2P / BR**2,
C     ZERO WHEN BELOW EPS; BOTH UNCHANGED WHEN THE POINT IS ON THE
C     DOUBLET LINE BEHIND IT, AND T2 WHEN ON IT AHEAD - TKER'S WAY). THE
C     GEOMETRY AND THE SERIES' EXPONENTIALS ONCE; THE REST PER FREQUENCY.
C
      INTEGER          NB,IAPX,N,NT,L
      REAL             X0,Y0,Z0,KRV(NB),BR,SGR,CGR,SGS,CGS,T1,T2,M
      DOUBLE PRECISION P1R(NB),P1I(NB),P2R(NB),P2I(NB)
      DOUBLE PRECISION X,Y,Z,R1,T1D,T2P,BETA2,BIGR,K1,K2,MU1,MU,C1,
     1                 C2,C3,C4,C5,C6,C7,C8,C9,E,PN(12),AN(12),EN(12),
     2                 DN,RN,QN,I0R,I0I,J0R,J0I,I00R,I00I,J00R,J00I,
     3                 I10R,I10I,I20R,I20I,I1R,I1I,I2R,I2I,CK1R,CK1I,
     4                 CK2R,CK2I,DK1R,DK1I,DK2R,DK2I,K10,K20,DKR,DBR,
     5                 EPS,B,C3G,C4G,C5G,C8G,RB2,S1,SI0,SJ0
      LOGICAL          DO1,DO2
      DOUBLE PRECISION AL(11),AD(12)
      DATA AL / .24186198D0, -2.7918027D0, 24.991079D0, -111.59196D0,
     1         271.43549D0, -305.75288D0, -41.18363D0, 545.98537D0,
     2         -644.78155D0, 328.72755D0, -64.279511D0 /
      DATA AD / 0.000319759140D0, -0.000055461471D0, 0.002726074362D0,
     1          0.005749551566D0, 0.031455895072D0, 0.106031126212D0,
     2          0.406838011567D0, 0.798112357155D0, -0.417749229098D0,
     3          0.077480713894D0, -0.012677284771D0, 0.001787032960D0 /
C
      EPS = 0.00001D0
      DO 5 L = 1,NB
      P1R(L) = 0.0D0
      P1I(L) = 0.0D0
      P2R(L) = 0.0D0
      P2I(L) = 0.0D0
    5 CONTINUE
      X   = DBLE(X0)
      Y   = DBLE(Y0)
      Z   = DBLE(Z0)
      DBR = DBLE(BR)
      R1  = SQRT(Y*Y + Z*Z)
      IF (R1 .GT. EPS) GO TO 200
      IF (X0 .LT. 0.0) RETURN
C     ON THE DOUBLET LINE, AHEAD OF THE RECEIVING POINT
      T1  = CGR*CGS + SGR*SGS
      T1D = DBLE(T1)
      DO 10 L = 1,NB
      C1  = DBLE(KRV(L))*X/DBR
      P1R(L) = 2.0D0*T1D*COS(C1) - 2.0D0*T1D
      P1I(L) =-2.0D0*T1D*SIN(C1)
   10 CONTINUE
      RETURN
C
C     THE GEOMETRY: WHICH KERNELS (T1, T2), R, U, THE STEADY PARTS
C
  200 T2P = Z*Z*DBLE(CGR)*DBLE(CGS) + Y*Y*DBLE(SGR)*DBLE(SGS)
     1    - Z*Y*(DBLE(SGR)*DBLE(CGS) + DBLE(CGR)*DBLE(SGS))
      T2  = SNGL(100.0D0*T2P/(DBR*DBR))
      DO2 = ABS(T2) .GE. EPS
      IF (.NOT.DO2) T2 = 0.0
      T1  = CGR*CGS + SGR*SGS
      DO1 = ABS(T1) .GE. EPS
      IF (.NOT.DO1) T1 = 0.0
      T1D = DBLE(T1)
      BETA2 = 1.0D0 - DBLE(M)*DBLE(M)
      BIGR  = SQRT(X*X + BETA2*R1*R1)
      MU1   = (DBLE(M)*BIGR - X)/(BETA2*R1)
      MU    = ABS(MU1)
      C3G   = DBLE(M)*R1/BIGR
      C4G   = SQRT(1.0D0 + MU*MU)
      C5G   = MU/C4G
      RB2   = BETA2*(R1/BIGR)**2
      C8G   = (RB2 + (2.0D0+MU1*C3G)/(C4G*C4G))*(-C3G/C4G)
      K10   = 1.0D0 + X/BIGR
      K20   = -2.0D0 - X*(2.0D0+RB2)/BIGR
C
C     THE SERIES' TERMS A(N) EXP(-P(N) U) (RODDEN ET AL. 1971, EQS. A.4
C     AND A.8) - LASCHKA P(N) = 0.372 N, E(N) = E(1)**N; DESMARAIS P(N)
C     = 2**N B, B = 0.009054814793, E(N) = E(N-1)**2 - ONE EXPONENTIAL
C
      IF (IAPX .EQ. 1) GO TO 210
      NT = 11
      DO 205 N = 1,NT
      AN(N) = AL(N)
      PN(N) = 0.372D0*DBLE(N)
  205 CONTINUE
      E     = EXP(-PN(1)*MU)
      EN(1) = E
      DO 207 N = 2,NT
  207 EN(N) = EN(N-1)*E
      GO TO 220
  210 NT = 12
      B  = 0.009054814793D0
      DO 215 N = 1,NT
      AN(N) = AD(N)
      PN(N) = (2.0D0**N)*B
  215 CONTINUE
      EN(1) = EXP(-PN(1)*MU)
      DO 217 N = 2,NT
  217 EN(N) = EN(N-1)*EN(N-1)
C
C     PER FREQUENCY: I0, J0 AT U AND AT 0, I1 AND 3 I2 (A.1, A.6), THE
C     REFLECTION FOR A NEGATIVE U, THE KERNELS AND THE PHASE KR X0 / BR
C
  220 DO 400 L = 1,NB
      DKR  = DBLE(KRV(L))
      K1   = DKR*R1/DBR
      K2   = K1*K1
      I0R  = 0.0D0
      S1   = 0.0D0
      J0R  = 0.0D0
      SJ0  = 0.0D0
      I00R = 0.0D0
      SI0  = 0.0D0
      J00R = 0.0D0
      J00I = 0.0D0
!GCC$ NOVECTOR
      DO 230 N = 1,NT
      DN   = 1.0D0/(PN(N)*PN(N) + K2)
      RN   = AN(N)*DN
      QN   = RN*DN
      I0R  = I0R + PN(N)*RN*EN(N)
      S1   = S1 + RN*EN(N)
      J0R  = J0R + QN*EN(N)*(PN(N)*PN(N) - K2 + PN(N)*MU/DN)
      SJ0  = SJ0 + QN*EN(N)*(2.0D0*PN(N) + MU/DN)
      I00R = I00R + PN(N)*RN
      SI0  = SI0 + RN
      J00R = J00R + QN*(PN(N)*PN(N) - K2)
      J00I = J00I + QN*2.0D0*PN(N)
  230 CONTINUE
      I0I  = -K1*S1
      J0I  = -K1*SJ0
      I00I = -K1*SI0
      J00I = -K1*J00I
      I10R = 1.0D0 + K1*I00I
      I10I = -K1*I00R
      I20R = 2.0D0 + K1*I00I + K2*J00R
      I20I = -K1*I00R + K2*J00I
      C6   = K1*MU
      C1   = SIN(C6)
      C2   = COS(C6)
      I1R  = C2*(1.0D0-C5G+K1*I0I) - C1*K1*I0R
      I1I  =-C2*K1*I0R - C1*(1.0D0-C5G+K1*I0I)
      I2R  = C2*(2.0D0*(1.0D0-C5G)-C5G/(1.0D0+MU*MU)+K1*I0I+K2*J0R)
     1     + C1*(C6*(1.0D0-C5G)-K1*I0R+K2*J0I)
      I2I  = C2*(C6*(1.0D0-C5G)-K1*I0R+K2*J0I)
     1     - C1*(2.0D0*(1.0D0-C5G)-C5G/(1.0D0+MU*MU)+K1*I0I+K2*J0R)
      IF (MU1 .LT. 0.0D0) I1R = 2.0D0*I10R - I1R
      IF (MU1 .LT. 0.0D0) I2R = 2.0D0*I20R - I2R
      IF (MU1 .NE. 0.0D0) GO TO 300
      I1R  = I10R
      I1I  = I10I
      I2R  = I20R
      I2I  = I20I
C     COS(K1 MU1) = COS(K1 MU); SIN(K1 MU1) = +-SIN(K1 MU)
  300 C3   = C2
      C4   = C1
      IF (MU1 .LT. 0.0D0) C4 = -C1
      C5   = DKR*X/DBR
      C6   = COS(C5)
      C7   = SIN(C5)
      IF (.NOT.DO1) GO TO 310
      CK1R = I1R + C3G*C3/C4G
      CK1I = I1I - C3G*C4/C4G
      DK1R = CK1R*C6 + CK1I*C7
      DK1I = CK1I*C6 - CK1R*C7
      P1R(L) = T1D*DK1R - K10*T1D
      P1I(L) = T1D*DK1I
  310 IF (.NOT.DO2) GO TO 400
      C9   = (K1*C3G)*(C3G/C4G)
      CK2R = -I2R + C8G*C3 - C9*C4
      CK2I = -I2I - C9*C3 - C8G*C4
      DK2R = CK2R*C6 + CK2I*C7
      DK2I = CK2I*C6 - CK2R*C7
      P2R(L) = T2P*DK2R - K20*T2P
      P2I(L) = T2P*DK2I
  400 CONTINUE
      RETURN
      END

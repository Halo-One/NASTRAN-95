      SUBROUTINE FA1PKQ (A,M1K,M1B,EIV,N)
C
C     HALO: FA1PKA, HSBG AND ATEIG AS ONE ROUTINE FOR THE PK METHOD -
C     THE EIGENVALUES OF THE 2N BY 2N STATE MATRIX  (0  I / M1K  M1B)
C     OF ONE PK ITERATION - WITH THE SAME ARITHMETIC IN THE SAME ORDER,
C     SO THE SAME BITS, BUT WITHOUT THE ARGUMENT ALIASING THE THREE
C     ORIGINALS ARE BUILT ON. FA1PKA PASSES ONE ARRAY TO HSBG AS BOTH
C     ITS REAL INPUT AND ITS DOUBLE PRECISION WORK (HSBG WIDENS IT IN
C     PLACE, BACKWARDS), AND ATEIG NARROWS ITS DOUBLE PRECISION RESULTS
C     BACK INTO THE SAME STORAGE AS REALS. THAT IS LEGAL AT -O0 ONLY BY
C     ACCIDENT; AN OPTIMISING COMPILER IS ENTITLED TO ASSUME THE DUMMY
C     ARGUMENTS DO NOT OVERLAP. HERE THE MATRIX IS BUILT IN DOUBLE
C     PRECISION DIRECTLY (THE VALUES HSBG'S WIDENING COPY WOULD HAVE
C     MADE, EXACTLY), THE EIGENVALUES ARE KEPT IN DOUBLE PRECISION
C     ARRAYS OF THEIR OWN, AND THE RESULT IS NARROWED ONCE, AS FA1PKA
C     LEFT IT: EIV(2I-1) = REAL PART, EIV(2I) = IMAGINARY PART.
C
C     THIS FILE IS COMPILED -O2 -FAUTOMATIC -FFP-CONTRACT=OFF (SEE
C     CMAKELISTS.TXT): NO STATIC LOCALS, NO COMMON, NO FUSED MULTIPLY-
C     ADD, SO IT IS BOTH THREAD SAFE AND BIT FOR BIT THE -O0 RESULT.
C     THE PK LOOP SPENDS NINE TENTHS OF ITS TIME HERE ON A 120 MODE
C     BASIS (A 240 BY 240 QR PER ITERATION PER ROOT).
C
C     A      WORK, (2N)**2 DOUBLE PRECISION (FA1PKE'S Z(IMA), 8 N**2
C            WORDS)
C     M1K    M-1 K, N BY N REAL, STORED AS FA1PKA READ IT
C     M1B    M-1 B, THE SAME
C     EIV    OUT, 4N REALS: THE 2N EIGENVALUES, REAL AND IMAGINARY
C            PARTS INTERLEAVED
C
      INTEGER          N,N2,I,J,K,IZ,IMK,IMI,IMB
      REAL             M1K(1),M1B(1),EIV(1)
      DOUBLE PRECISION A(1)
      DOUBLE PRECISION RR(2*N),RI(2*N)
      INTEGER          IANA(2*N)
C
C     THE MATRIX, AS FA1PKA WROTE IT AND HSBG WIDENED IT: COLUMNS 1..N
C     ARE (0 / M1K), COLUMNS N+1..2N ARE (I / M1B)
C
      N2  = N*2
      IZ  = 0
      IMK = N
      IMI = N*N*2
      IMB = IMI + N
      K   = 0
      DO 10 I = 1,N
      DO 20 J = 1,N
      K = K + 1
      A(IZ +J) = 0.0D0
      A(IMK+J) = DBLE(M1K(K))
      A(IMB+J) = DBLE(M1B(K))
      A(IMI+J) = 0.0D0
      IF (I .EQ. J) A(IMI+J) = 1.0D0
   20 CONTINUE
      IZ  = IZ  + N2
      IMK = IMK + N2
      IMI = IMI + N2
      IMB = IMB + N2
   10 CONTINUE
      CALL HSBGQ  (N2,A,N2)
      CALL ATEIGQ (N2,A,RR,RI,IANA,N2)
      DO 30 I = 1,N2
      EIV(2*I-1) = SNGL(RR(I))
      EIV(2*I  ) = SNGL(RI(I))
   30 CONTINUE
      RETURN
      END

      SUBROUTINE HSBGQ (N,A,IA)
C
C     HALO: HSBG (REDUCTION TO UPPER HESSENBERG FORM BY STABILISED
C     ELEMENTARY SIMILARITY TRANSFORMATIONS) WITHOUT ITS OPENING COPY
C     OF A REAL ARRAY INTO THE SAME STORAGE AS DOUBLE PRECISION - THE
C     CALLER (FA1PKQ) HAS BUILT A IN DOUBLE PRECISION. THE REST IS
C     NASA'S HSBG STATEMENT FOR STATEMENT.
C
      INTEGER          N,IA,L,NIA,LIA,L1,L2,ISUB,IPIV,M,I,J,K,LJ,KJ,
     1                 KL,LK,JK
      DOUBLE PRECISION A(1),PIV,S,T
      L=N
      NIA=L*IA
      LIA=NIA-IA
   20 IF(L-3) 360,40,40
   40 LIA=LIA-IA
      L1=L-1
      L2=L1-1
      ISUB=LIA+L
      IPIV=ISUB-IA
      PIV=DABS(A(IPIV))
      IF(L-3) 90,90,50
   50 M=IPIV-IA
      DO 80 I=L,M,IA
      T=DABS(A(I))
      IF(T-PIV) 80,80,60
   60 IPIV=I
      PIV=T
   80 CONTINUE
   90 IF(PIV) 100,320,100
  100 IF(PIV-DABS(A(ISUB))) 180,180,120
  120 M=IPIV-L
      DO 140 I=1,L
      J=M+I
      T=A(J)
      K=LIA+I
      A(J)=A(K)
  140 A(K)=T
      M=L2-M/IA
      DO 160 I=L1,NIA,IA
      T=A(I)
      J=I-M
      A(I)=A(J)
  160 A(J)=T
  180 DO 200 I=L,LIA,IA
      A(I)=A(I)/A(ISUB)
  200 CONTINUE
      J=-IA
      DO 240 I=1,L2
      J=J+IA
      LJ=L+J
      DO 220 K=1,L1
      KJ=K+J
      KL=K+LIA
      A(KJ)=A(KJ)-A(LJ)*A(KL)
  220 CONTINUE
  240 CONTINUE
      K=-IA
      DO 300 I=1,N
      K=K+IA
      LK=K+L1
      S=A(LK)
      LJ=L-IA
      DO 280 J=1,L2
      JK=K+J
      LJ=LJ+IA
      S=S+A(LJ)*A(JK)
  280 CONTINUE
  300 A(LK)=S
      DO 310 I=L,LIA,IA
  310 A(I)=0.0
  320 L=L1
      GO TO 20
  360 RETURN
      END

      SUBROUTINE ATEIGQ (M,A,RR,RI,IANA,IA)
C
C     HALO: ATEIG (THE EIGENVALUES OF AN UPPER HESSENBERG MATRIX BY THE
C     DOUBLE-SHIFT QR ITERATION) WITHOUT ITS CLOSING COPY OF RR, RI AND
C     A INTO THE SAME STORAGE AS REALS - FA1PKQ NARROWS THE EIGENVALUES
C     ITSELF AND NOTHING READS THE REDUCED MATRIX AFTERWARDS. THE REST
C     IS NASA'S ATEIG STATEMENT FOR STATEMENT, INCLUDING ITS ONE READ
C     OUTSIDE THE MATRIX: THE SEARCH FOR A SMALL SUBDIAGONAL ELEMENT AT
C     620-660 TAKES ONE STEP PAST ELEMENT (2,1), TO 'ELEMENT (1,0)',
C     A(1-IA) - THE DOUBLE 2*IA WORDS BELOW A(1) - AND WHETHER THAT IS
C     BELOW EPS DECIDES WHETHER THE QR SWEEP STARTS AT ROW 1 OR ROW 2.
C     THE ROOTS MOVE IN THE SIXTH DIGIT WITH IT. IT IS LEFT AS NASA
C     WROTE IT, SO THAT THE ROOTS ARE THE SERIAL SOLVE'S TO THE BIT, AND
C     THE CALLER HAS TO PUT THE SAME BYTES THERE: FA1PKE HAS THE TOP OF
C     M-1 B BELOW Z(IMA), AND FA1PKP LAYS ITS THREADS' ARRAYS OUT THE
C     SAME WAY. WITH A SEPARATELY ALLOCATED MATRIX THE READ IS OF SOME
C     OTHER MEMORY, OR OF NONE (A SEGMENTATION FAULT).
C
      INTEGER          M,IA,IANA(1),P,P1,Q,MAXIT,N,N1,IN,NN,NP,IT,I,N2,
     1                 IN1,NN1,N1N,N1N1,N1N2,J,K,IPI,IPIP,IPIP2,II,II1,
     2                 IIP,IJ,IP2J,IP,JIP,JI,JIP2
      DOUBLE PRECISION A(1),RR(1),RI(1),PRR(2),PRI(2)
      DOUBLE PRECISION ALPHA,CAP,D,DELTA,EPS,ETA,E10,E6,E7,G1,G2,G3
      DOUBLE PRECISION PAN,PAN1,PSI1,PSI2,R,RMOD,S,T,U,V
      E7=1.0E-8
      E6=1.0E-6
      E10=1.0E-10
      DELTA=0.5
      MAXIT=30
      N=M
   20 N1=N-1
      IN=N1*IA
      NN=IN+N
      IF(N1) 30,1300,30
   30 NP=N+1
      IT=0
      DO 40 I=1,2
      PRR(I)=0.0
   40 PRI(I)=0.0
      PAN=0.0
      PAN1=0.0
      R=0.0
      S=0.0
      N2=N1-1
      IN1=IN-IA
      NN1=IN1+N
      N1N=IN+N1
      N1N1=IN1+N1
   60 T=A(N1N1)-A(NN)
      U=T*T
      V=4.0D0*A(N1N)*A(NN1)
      IF (DABS(V)-U*E7) 100,100,65
   65 T=U+V
      IF (DABS(T)-DMAX1(U,DABS(V))*E6) 67,67,68
   67 T=0.0
   68 U=(A(N1N1)+A(NN))/2.0D0
      V=DSQRT(DABS(T))/2.0D0
      IF(T)140,70,70
   70 IF(U) 80,75,75
   75 RR(N1)=U+V
      RR(N)=U-V
      GO TO 130
   80 RR(N1)=U-V
      RR(N)=U+V
      GO TO 130
  100 IF(T)120,110,110
  110 RR(N1)=A(N1N1)
      RR(N)=A(NN)
      GO TO 130
  120 RR(N1)=A(NN)
      RR(N)=A(N1N1)
  130 RI(N)=0.0
      RI(N1)=0.0
      GO TO 160
  140 RR(N1)=U
      RR(N)=U
      RI(N1)=V
      RI(N)=-V
  160 IF(N2)1280,1280,180
  180 N1N2=N1N1-IA
      RMOD=RR(N1)*RR(N1)+RI(N1)*RI(N1)
      EPS=E10*DSQRT(RMOD)
      IF(DABS(A(N1N2))-EPS)1280,1280,240
  240 IF(DABS(A(NN1))-E10*DABS(A(NN))) 1300,1300,250
  250 IF(DABS(PAN1-A(N1N2))-DABS(A(N1N2))*E6) 1240,1240,260
  260 IF(DABS(PAN-A(NN1))-DABS(A(NN1))*E6) 1240,1240,300
  300 IF(IT-MAXIT) 320,1240,1240
  320 J=1
      DO 360 I=1,2
      K=NP-I
      IF(DABS(RR(K)-PRR(I))+DABS(RI(K)-PRI(I))-DELTA*(DABS(RR(K))
     *   +DABS(RI(K)))) 340,360,360
  340 J=J+I
  360 CONTINUE
      GO TO (440,460,460,480),J
  440 R=0.0
      S=0.0
      GO TO 500
  460 J=N+2-J
      R=RR(J)*RR(J)
      S=RR(J)+RR(J)
      GO TO 500
  480 R=RR(N)*RR(N1)-RI(N)*RI(N1)
      S=RR(N)+RR(N1)
  500 PAN=A(NN1)
      PAN1=A(N1N2)
      DO 520 I=1,2
      K=NP-I
      PRR(I)=RR(K)
  520 PRI(I)=RI(K)
      P=N2
      IPI = N1N2
      DO 580 J=2,N2
      IPI = IPI - IA - 1
      IF(DABS(A(IPI))-EPS) 600,600,530
  530 IPIP=IPI+IA
      IPIP2=IPIP+IA
      D=A(IPIP)*(A(IPIP)-S)+A(IPIP2)*A(IPIP+1)+R
      IF(D)540,560,540
  540 IF(DABS(A(IPI)*A(IPIP+1))*(DABS(A(IPIP)+A(IPIP2+1)-S)+
     * DABS(A(IPIP2+2)))-DABS(D)*EPS) 620,620,560
  560 P=N1-J
  580 CONTINUE
  600 Q=P
      GO TO 680
  620 P1=P-1
      Q = P
      DO 660 I = 1,P1
      IPI = IPI - IA - 1
      IF(DABS(A(IPI))-EPS) 680,680,660
  660 Q=Q-1
  680 II=(P-1)*IA+P
      DO 1220 I=P,N1
      II1=II-IA
      IIP=II+IA
      IF(I-P)720,700,720
  700 IPI=II+1
      IPIP=IIP+1
      G1=A(II)*(A(II)-S)+A(IIP)*A(IPI)+R
      G2=A(IPI)*(A(IPIP)+A(II)-S)
      G3=A(IPI)*A(IPIP+1)
      A(IPI+1)=0.0
      GO TO 780
  720 G1=A(II1)
      G2=A(II1+1)
      IF(I-N2)740,740,760
  740 G3=A(II1+2)
      GO TO 780
  760 G3=0.0
  780 CAP=DSQRT(G1*G1+G2*G2+G3*G3)
      IF(CAP)800,860,800
  800 IF(G1)820,840,840
  820 CAP=-CAP
  840 T=G1+CAP
      PSI1=G2/T
      PSI2=G3/T
      ALPHA=2.0D0/(1.0D0+PSI1*PSI1+PSI2*PSI2)
      GO TO 880
  860 ALPHA=2.0
      PSI1=0.0
      PSI2=0.0
  880 IF(I-Q)900,960,900
  900 IF(I-P)920,940,920
  920 A(II1)=-CAP
      GO TO 960
  940 A(II1)=-A(II1)
  960 IJ=II
      DO 1040 J=I,N
      T=PSI1*A(IJ+1)
      IF(I-N1)980,1000,1000
  980 IP2J=IJ+2
      T=T+PSI2*A(IP2J)
 1000 ETA=ALPHA*(T+A(IJ))
      A(IJ)=A(IJ)-ETA
      A(IJ+1)=A(IJ+1)-PSI1*ETA
      IF(I-N1)1020,1040,1040
 1020 A(IP2J)=A(IP2J)-PSI2*ETA
 1040 IJ=IJ+IA
      IF(I-N1)1080,1060,1060
 1060 K=N
      GO TO 1100
 1080 K=I+2
 1100 IP=IIP-I
      DO 1180 J=Q,K
      JIP=IP+J
      JI=JIP-IA
      T=PSI1*A(JIP)
      IF(I-N1)1120,1140,1140
 1120 JIP2=JIP+IA
      T=T+PSI2*A(JIP2)
 1140 ETA=ALPHA*(T+A(JI))
      A(JI)=A(JI)-ETA
      A(JIP)=A(JIP)-ETA*PSI1
      IF(I-N1)1160,1180,1180
 1160 A(JIP2)=A(JIP2)-ETA*PSI2
 1180 CONTINUE
      IF(I-N2)1200,1220,1220
 1200 JI=II+3
      JIP=JI+IA
      JIP2=JIP+IA
      ETA=ALPHA*PSI2*A(JIP2)
      A(JI)=-ETA
      A(JIP)=-ETA*PSI1
      A(JIP2)=A(JIP2)-ETA*PSI2
 1220 II=IIP+1
      IT=IT+1
      GO TO 60
 1240 IF(DABS(A(NN1))-DABS(A(N1N2))) 1300,1280,1280
 1280 IANA(N)=0
      IANA(N1)=2
      N=N2
      IF(N2)1400,1400,20
 1300 RR(N)=A(NN)
      RI(N)=0.0
      IANA(N)=1
      IF(N1)1400,1400,1320
 1320 N=N1
      GO TO 20
 1400 RETURN
      END

      SUBROUTINE FA1PKG (A,B,C,N)
C
C     HALO: GMMATS (A,N,N,0, B,N,N,0, C) - C = A*B FOR SQUARE N BY N
C     REAL MATRICES STORED BY ROWS - WITH GMMATS'S SINGLE PRECISION
C     ACCUMULATION: EACH C(I,J) SUMMED OVER K = 1..N IN ORDER FROM 0.
C     THE TWO PRODUCTS OF EVERY PK ITERATION (FA1PKE). C MUST NOT
C     OVERLAP A OR B, WHICH FA1PKE'S USE SATISFIES.
C
C     GMMATS RUNS K INNERMOST, DOWN A COLUMN OF B (A STRIDE OF N). HERE
C     J IS INNERMOST: ROW I OF C GETS A(I,K) TIMES ROW K OF B ADDED FOR
C     K = 1..N IN TURN - EVERY C(I,J) THE SAME SUM IN THE SAME ORDER,
C     AND THE INNER LOOP CONTIGUOUS AND VECTORISED (NOT A REDUCTION).
C     5.6 TIMES FASTER AT 120 MODES, THE SAME BITS.
C
      INTEGER N,I,J,K,IFIX,KB
      REAL    A(1),B(1),C(1),AK
      DO 30 I = 1,N
      IFIX = (I-1)*N
      DO 5 J = 1,N
    5 C(IFIX+J) = 0.0
      DO 20 K = 1,N
      AK = A(IFIX+K)
      KB = (K-1)*N
      DO 10 J = 1,N
      C(IFIX+J) = C(IFIX+J) + AK*B(KB+J)
   10 CONTINUE
   20 CONTINUE
   30 CONTINUE
      RETURN
      END
